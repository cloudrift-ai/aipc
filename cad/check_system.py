"""System check: spec lint, compatibility, assembly coverage, renders and datasheets.

Run after ``make cad`` (and ``make render``). Writes
  models/compatibility-report.json   machine-readable results
  docs/system-check.md               human-readable report (committed)
  parts/README.md                    index of all parts
  parts/<category>/<id>/README.md    generated text spec per part

Exit status 1 when any check FAILs, a spec is malformed or the assembly
coverage is broken. BLOCKED and PROVISIONAL items are reported, not fatal:
they are the open questions a design audit must list.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from datetime import date

from aipc import paths, spec
from aipc.compat import run_checks
from aipc.partdocs import write_part_docs

ICON = {"FAIL": "FAIL", "BLOCKED": "BLOCKED", "PROVISIONAL": "provisional", "PASS": "pass"}


def gather():
    parts = spec.load_all()
    lint = spec.lint(parts)
    checks = run_checks()
    bom_path = paths.MODELS / "assembly-bom.json"
    bom = json.loads(bom_path.read_text()) if bom_path.exists() else {"parts": {}, "errors": ["models/assembly-bom.json missing: run make cad"]}

    coverage = []
    for pid, row in bom["parts"].items():
        if pid not in parts:
            bom["errors"].append(f"assembly-bom lists {pid} but no part folder exists: rerun make cad")
            continue
        if row["state"] == "not_modeled":
            coverage.append({"part": pid, "status": "BLOCKED", "detail": f"not in the assembly: {row['not_modeled']}"})
    for pid in parts:
        if pid not in bom["parts"]:
            bom["errors"].append(f"{pid} has a folder but is not in models/assembly-bom.json: rerun make cad")

    fit = paths.MODELS / "fit-report.json"
    if fit.exists():
        planned = json.loads(fit.read_text()).get("planned_upgrade_clearance", {})
        for c in planned.get("component_conflicts", []) + planned.get("cable_conflicts", []):
            names = c.get("components") or c.get("cables") or c.get("items") or []
            coverage.append({"part": " / ".join(map(str, names)) or "layout",
                             "status": "BLOCKED", "detail": f"geometry conflict in the layout: {c.get('status', c)}"})

    renders = []
    for p in parts.values():
        if p.model_step.exists():
            if not p.render_png.exists() or p.render_png.stat().st_mtime < p.model_step.stat().st_mtime:
                renders.append(f"{p.id}: render.png missing or older than its model (run make render)")
    assembly_png = paths.RENDERS / "assembly.png"
    if not assembly_png.exists() or assembly_png.stat().st_mtime < (paths.MODELS / "dual-pc-hammond-assembly.step").stat().st_mtime:
        renders.append("models/renders/assembly.png missing or older than the assembly (run make render)")

    datasheets = []
    for p in parts.values():
        if p.category != "purchased" or p.status == "unspecified":
            continue
        if not p.datasheets:
            datasheets.append({"part": p.id, "status": "BLOCKED", "detail": p.data.get("no_datasheet_reason", "no datasheet")})
        for ds in p.datasheets:
            local = p.dir / "datasheets"
            have = local.exists() and any(local.iterdir())
            if not have:
                datasheets.append({"part": p.id, "status": "PROVISIONAL", "detail": f"not fetched locally: {ds['url']} (run make datasheets)"})

    weak = {}
    for p in parts.values():
        counts = Counter(d.evidence for d in p.dims.values())
        weak_n = sum(n for ev, n in counts.items() if ev not in spec.STRONG_EVIDENCE)
        if weak_n:
            weak[p.id] = dict(counts)

    unspecified = [p.id for p in parts.values() if p.status == "unspecified"]
    return parts, lint, checks, bom, coverage, renders, datasheets, weak, unspecified


def write_reports(parts, lint, checks, bom, coverage, renders, datasheets, weak, unspecified):
    summary = Counter(c["status"] for c in checks + coverage)
    report = {"date": date.today().isoformat(), "summary": dict(summary), "lint": lint,
              "assembly_errors": bom["errors"], "checks": checks, "coverage": coverage,
              "renders": renders, "datasheets": datasheets, "weak_evidence_dims": weak,
              "unspecified_parts": unspecified}
    (paths.MODELS / "compatibility-report.json").write_text(json.dumps(report, indent=2) + "\n")

    L = ["# System check", "",
         "Generated by `make check` from the part specs in [parts/](../parts/README.md), the assembly "
         "coverage in [models/assembly-bom.json](../models/assembly-bom.json) and the renders. "
         "Do not edit by hand.", "",
         "Statuses: **FAIL** means declared data conflicts; **BLOCKED** means the data needed to decide is missing; "
         "**provisional** means it passes, but on weak evidence (listing, photo estimate, allowance, assumption) "
         "or a configured limit; **pass** means it passes on datasheet, standard or measured values only. "
         "A check run against the same assumed numbers does not validate them.", "",
         f"**Summary:** " + ", ".join(f"{n} {ICON[s]}" for s, n in sorted(summary.items(), key=lambda kv: ["FAIL", "BLOCKED", "PROVISIONAL", "PASS"].index(kv[0]))), ""]
    if lint or bom["errors"] or renders:
        L += ["## Process errors", ""] + [f"- {e}" for e in lint + bom["errors"] + renders] + [""]
    if unspecified:
        L += ["## Unspecified parts", "", "These parts have not been chosen, so nothing that depends on them can be checked:", ""]
        L += [f"- [{pid}](../{parts[pid].dir.relative_to(paths.ROOT)}/README.md): {parts[pid].role}" for pid in unspecified] + [""]
    L += ["## Compatibility", "", "| Status | Rule | Interface | Detail |", "| --- | --- | --- | --- |"]
    for c in checks:
        detail = c["detail"].replace("|", "/")
        if c.get("note"):
            detail += f" ({c['note']})"
        L.append(f"| {ICON[c['status']]} | {c['rule']} | `{c['type']}` | {detail} |")
    L += ["", "## Assembly coverage", "",
          "Every assembly instance belongs to a part folder or a declared keepout. Parts not in the assembly, and unresolved geometry conflicts the layout reports:", ""]
    L += [f"- **{c['part']}**: {c['detail']}" for c in coverage] or ["- none"]
    L += ["", "## Datasheets", ""]
    missing = [d for d in datasheets if d["status"] == "BLOCKED"]
    L += [f"- **{d['part']}**: no datasheet recorded. {d['detail']}" for d in missing] or ["- every purchased part lists a datasheet"]
    unfetched = sorted({d["part"] for d in datasheets if d["status"] == "PROVISIONAL"})
    if unfetched:
        L += ["", f"Not fetched locally (run `make datasheets`): {', '.join(unfetched)}."]
    L += ["", "## Weak-evidence dimensions", "", "Dimensions not backed by a datasheet, standard or measurement, by part:", ""]
    L += [f"- {pid}: " + ", ".join(f"{n} {ev}" for ev, n in sorted(c.items())) for pid, c in sorted(weak.items())]
    (paths.ROOT / "docs" / "system-check.md").write_text("\n".join(L) + "\n")
    write_part_docs(parts, checks, bom)
    return summary


def main():
    results = gather()
    summary = write_reports(*results)
    parts, lint, checks, bom, *_ = results
    print("check:", dict(summary), "| lint:", len(lint), "| assembly errors:", len(bom["errors"]))
    for c in checks:
        if c["status"] in ("FAIL", "BLOCKED"):
            print(f"  {c['status']:8} {c['type']}: {c['detail']}")
    fatal = summary.get("FAIL", 0) or lint or bom["errors"]
    if fatal:
        print("make check: FAIL (see docs/system-check.md)")
    return 1 if fatal else 0


if __name__ == "__main__":
    sys.exit(main())
