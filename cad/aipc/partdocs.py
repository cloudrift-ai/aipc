"""Generated README.md per part folder and the parts/README.md index."""
from __future__ import annotations

from . import paths

ICON = {"FAIL": "FAIL", "BLOCKED": "BLOCKED", "PROVISIONAL": "provisional", "PASS": "pass"}


def _fmt(v):
    if v is None:
        return "**unknown**"
    return f"{v:g}" if isinstance(v, float) else str(v)


def _iface(i):
    bits = [f"`{i['type']}`"]
    for key in ("value", "accepts", "count", "capacity", "load", "load_limited", "min", "max"):
        if key in i:
            bits.append(f"{key} {_fmt(i[key])}")
    if i.get("unit"):
        bits.append(i["unit"])
    bits.append(f"({i['evidence']})")
    if i.get("note"):
        bits.append(f"— {i['note']}")
    return " ".join(bits)


def part_readme(p, checks, bom_row) -> str:
    L = [f"# {p.name}", "",
         "<!-- Generated by make check from part.toml. Edit part.toml, not this file. -->", "",
         f"| | |", "| --- | --- |",
         f"| ID | `{p.id}` |", f"| Category | {p.category} |", f"| Role | {p.role} |",
         f"| Status | {p.status} |", f"| Quantity | {p.quantity} |", f"| Systems | {', '.join(p.systems)} |"]
    if p.data.get("print"):
        pr = p.data["print"]
        L.append(f"| Print | plate `{pr.get('plate')}`, {pr.get('material')} |")
    links = p.data.get("links", {})
    for k, v in links.items():
        L.append(f"| {k.capitalize()} | <{v}> |")
    L.append("")
    if p.data.get("notes"):
        L += [p.data["notes"].strip(), ""]
    if p.render_png.exists():
        L += ["![Part views](render.png)", ""]
    if (p.dir / "in-assembly.png").exists():
        L += ["![Part in the assembly](in-assembly.png)", ""]

    L += ["## Model", ""]
    m = p.data.get("model", {})
    if p.model_step.exists():
        L.append(f"- [{p.model_step.name}]({p.model_step.name})" + (f" and [{p.model_stl.name}]({p.model_stl.name})" if p.model_stl.exists() else ""))
    L.append(f"- Source: {m.get('source', 'unknown')}" + (f". {m['notes']}" if m.get("notes") else ""))
    if m.get("vendor_cad"):
        L.append(f"- Vendor CAD: {m['vendor_cad']}")
    if bom_row:
        state = bom_row["state"]
        detail = {"modeled": f"{bom_row['instances']} instances in the assembly",
                  "covered": f"inside the envelope of `{bom_row['covered_by']}`",
                  "not_modeled": f"**not in the assembly**: {bom_row['not_modeled']}"}.get(state, state)
        L.append(f"- Assembly: {detail}")
    L.append("")

    L += ["## Datasheets", ""]
    if p.datasheets:
        L += [f"- [{d['title']}]({d['url']})" for d in p.datasheets]
        L.append("- Local copies: `datasheets/` after `make datasheets` (not committed)")
    else:
        L.append(f"- None recorded. {p.data.get('no_datasheet_reason', '')}")
    L.append("")

    if p.dims:
        L += ["## Dimensions", "", "| Key | Value | Evidence | Source / note |", "| --- | --- | --- | --- |"]
        for d in p.dims.values():
            src = "; ".join(x for x in (d.source, d.note) if x)
            L.append(f"| {d.key} | {_fmt(d.value)} {d.unit if d.value is not None else ''} | {d.evidence} | {src} |")
        L.append("")
    if p.provides or p.requires:
        L += ["## Interfaces", ""]
        L += [f"- provides {_iface(i)}" for i in p.provides]
        L += [f"- requires {_iface(i)}" for i in p.requires]
        L.append("")
    mine = [c for c in checks if p.id in c.get("requirers", []) or p.id in c.get("providers", [])
            or p.id in c.get("contributors", [])]
    if mine:
        L += ["## Compatibility checks", "", "| Status | Rule | Interface | Detail |", "| --- | --- | --- | --- |"]
        L += [f"| {ICON[c['status']]} | {c['rule']} | `{c['type']}` | {c['detail'].replace('|', '/')} |" for c in mine]
        L.append("")
    return "\n".join(L)


def write_part_docs(parts, checks, bom):
    for p in parts.values():
        (p.dir / "README.md").write_text(part_readme(p, checks, bom["parts"].get(p.id)) + "\n")
    worst = {}
    order = ["FAIL", "BLOCKED", "PROVISIONAL", "PASS"]
    for c in checks:
        for pid in set(c.get("requirers", [])) | set(c.get("providers", [])):
            if pid in parts and (pid not in worst or order.index(c["status"]) < order.index(worst[pid])):
                worst[pid] = c["status"]
    L = ["# Parts", "",
         "<!-- Generated by make check. Edit each part.toml, not this file. -->", "",
         "One folder per part: `part.toml` (spec, evidence, interfaces), a generated `README.md`, "
         "the model used in the assembly (`<id>.step`), `render.png` and `in-assembly.png`, "
         "and fetched `datasheets/`. See [docs/process.md](../docs/process.md) for the workflow and "
         "[docs/system-check.md](../docs/system-check.md) for the latest compatibility results.", ""]
    for category in paths.CATEGORIES:
        rows = [p for p in parts.values() if p.category == category]
        if not rows:
            continue
        L += [f"## {category.capitalize()}", "", "| Part | Qty | Status | Systems | Worst check | Role |", "| --- | ---: | --- | --- | --- | --- |"]
        for p in sorted(rows, key=lambda p: p.id):
            rel = p.dir.relative_to(paths.PARTS)
            L.append(f"| [{p.id}]({rel}/README.md) | {p.quantity} | {p.status} | {', '.join(p.systems)} | "
                     f"{ICON.get(worst.get(p.id), '-')} | {p.role} |")
        L.append("")
    (paths.PARTS / "README.md").write_text("\n".join(L) + "\n")
