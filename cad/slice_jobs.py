"""Slice the print plates in print/ for the first-generation Qidi X-Plus.

Needs OrcaSlicer (macOS app, Linux AppImage/binary or Flatpak) with its bundled
Qidi system presets. Override detection with ORCA="<command>" and
ORCA_MACHINE=<path to "Qidi X-Plus 0.4 nozzle.json">. Pass plate names
(e.g. 05_psu_brackets) to slice only those. The G-code is for fit prototypes
until the physical shelf is measured; it is gitignored and regenerated by make.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
JOBS = ROOT / "print"
PROFILES = JOBS / "profiles"
GCODE = JOBS / "gcode"
MACHINE_PRESET = "system/Qidi/machine/Qidi X-Plus 0.4 nozzle.json"
ORCA_CONFIG_DIRS = (
    Path.home() / "Library/Application Support/OrcaSlicer",  # macOS
    Path.home() / ".config/OrcaSlicer",  # Linux binary/AppImage
    Path.home() / ".var/app/com.orcaslicer.OrcaSlicer/config/OrcaSlicer",  # Flatpak
)
ORCA_MAC_APP = Path("/Applications/OrcaSlicer.app/Contents/MacOS/OrcaSlicer")


def find_machine() -> Path:
    if "ORCA_MACHINE" in os.environ:
        return Path(os.environ["ORCA_MACHINE"])
    for config in ORCA_CONFIG_DIRS:
        if (config / MACHINE_PRESET).exists():
            return config / MACHINE_PRESET
    raise SystemExit("Qidi X-Plus preset not found; start OrcaSlicer once or set ORCA_MACHINE")


def find_orca() -> list[str]:
    if "ORCA" in os.environ:
        return shlex.split(os.environ["ORCA"])
    if ORCA_MAC_APP.exists():
        return [str(ORCA_MAC_APP)]
    for name in ("orca-slicer", "OrcaSlicer"):
        if shutil.which(name):
            return [name]
    if shutil.which("flatpak"):
        return ["flatpak", "run", "com.orcaslicer.OrcaSlicer"]
    raise SystemExit("OrcaSlicer not found; install it or set ORCA")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def validate_gcode(path: Path, expected_height: float, supports_required: bool = False, *, nozzle_c=240, bed_c=75, ht_pla_gf=False) -> dict:
    text = path.read_text()
    assert re.search(r"generated by OrcaSlicer \d", text), path.name
    assert "bed_shape = 0x0,270x0,270x200,0x200" in text
    assert f"M190 S{bed_c}" in text and f"M109 S{nozzle_c}" in text
    if ht_pla_gf:
        for key,value in {"nozzle_type":"hardened_steel","filament_type":"PLA","filament_density":"1.337","fan_min_speed":"100","fan_max_speed":"100"}.items():
            assert re.search(rf"^; {key} = {re.escape(value)}$",text,re.MULTILINE),(path.name,key)
    if "mobo_adapter" in path.name:
        assert "; skirt_loops = 0" in text
    assert ";TYPE:Brim" in text
    assert "; layer_change_gcode = G92 E0" in text or "\nG92 E0\n" in text
    assert f"; enable_support = {int(supports_required)}" in text
    if supports_required:
        assert ";TYPE:Support" in text and ";TYPE:Support interface" in text, "No actual support paths"
        for key, value in {"support_type": "normal(auto)", "support_style": "snug",
                           "support_threshold_angle": "45", "support_on_build_plate_only": "0",
                           "support_top_z_distance": "0.2", "support_object_xy_distance": "0.4",
                           "support_speed": "30", "support_interface_speed": "25"}.items():
            assert re.search(rf"^; {key} = {re.escape(value)}$", text, re.MULTILINE), (path.name, key)
    assert "; wall_loops = 4" in text
    assert "; sparse_infill_density = 40%" in text
    required_settings = {
        "nozzle_diameter": "0.4",
        "layer_height": "0.2",
        "filament_max_volumetric_speed": "5",
        "initial_layer_speed": "15",
        "initial_layer_infill_speed": "15",
        "skirt_speed": "15",
        "outer_wall_speed": "25",
        "inner_wall_speed": "30",
        "sparse_infill_speed": "35",
        "internal_solid_infill_speed": "35",
        "top_surface_speed": "25",
        "travel_speed": "100",
        "default_acceleration": "300",
        "initial_layer_acceleration": "200",
        "travel_acceleration": "500",
    }
    for key, value in required_settings.items():
        assert re.search(rf"^; {key} = {re.escape(value)}$", text, re.MULTILINE), (path.name, key)
    assert "M104 S0" in text and "M140 S0" in text

    temperature_commands = []
    xy_bounds = [float("inf"), float("inf"), float("-inf"), float("-inf")]
    x = y = 0.0
    extrusion = feed_mm_min = 0.0
    relative_extrusion = False
    layer_number = 0
    print_acceleration = travel_acceleration = None
    max_print_speed = max_travel_speed = max_first_layer_speed = 0.0
    max_print_acceleration = max_travel_acceleration = 0.0
    max_first_layer_acceleration = 0.0
    role = ""
    max_brim_speed = 0.0
    for raw in text.splitlines():
        if raw.startswith(";TYPE:"):
            role = raw.removeprefix(";TYPE:").strip()
        if raw == ";LAYER_CHANGE":
            layer_number += 1
        line = raw.split(";", 1)[0].strip()
        if not line:
            continue
        command = line.split()[0]
        parameters = {key: float(value) for key, value in re.findall(r"\b([A-Z])(-?(?:\d+(?:\.\d*)?|\.\d+))", line)}
        assert command not in {"G91", "G2", "G3"}, (path.name, "unsupported motion mode", line)
        if command in {"M82", "M83"}:
            relative_extrusion = command == "M83"
        if command == "G92" and "E" in parameters:
            extrusion = parameters["E"]
        if command == "M204":
            if "S" in parameters:
                print_acceleration = travel_acceleration = parameters["S"]
            print_acceleration = parameters.get("P", print_acceleration)
            travel_acceleration = parameters.get("T", travel_acceleration)
        if command in {"M104", "M109"}:
            match = re.search(r"\b[SR](-?\d+(?:\.\d+)?)", line)
            if match:
                temperature_commands.append(float(match.group(1)))
        if command in {"G0", "G1"}:
            feed_mm_min = parameters.get("F", feed_mm_min)
            delta_e = parameters.get("E", 0.0) if relative_extrusion else parameters.get("E", extrusion) - extrusion
            if "E" in parameters:
                extrusion = extrusion + delta_e if relative_extrusion else parameters["E"]
            xy_move = parameters.get("X", x) != x or parameters.get("Y", y) != y
            if xy_move and layer_number:
                speed = feed_mm_min / 60
                if delta_e > 0:
                    assert speed <= 35.01, (path.name, "print speed", speed)
                    assert print_acceleration is not None and print_acceleration <= 300, (path.name, "print acceleration", print_acceleration)
                    max_print_speed = max(max_print_speed, speed)
                    max_print_acceleration = max(max_print_acceleration, print_acceleration)
                    if role == "Brim":
                        assert speed <= 15.01, (path.name, "brim speed", speed)
                        max_brim_speed = max(max_brim_speed, speed)
                    if layer_number == 1:
                        assert speed <= 15.01 and print_acceleration <= 200, (path.name, "first layer", speed, print_acceleration)
                        max_first_layer_speed = max(max_first_layer_speed, speed)
                        max_first_layer_acceleration = max(max_first_layer_acceleration, print_acceleration)
                else:
                    assert speed <= 100.01, (path.name, "travel speed", speed)
                    assert travel_acceleration is not None and travel_acceleration <= 500, (path.name, "travel acceleration", travel_acceleration)
                    max_travel_speed = max(max_travel_speed, speed)
                    max_travel_acceleration = max(max_travel_acceleration, travel_acceleration)
            x = parameters.get("X", x)
            y = parameters.get("Y", y)
            if "X" in parameters or "Y" in parameters:
                xy_bounds[0] = min(xy_bounds[0], x)
                xy_bounds[1] = min(xy_bounds[1], y)
                xy_bounds[2] = max(xy_bounds[2], x)
                xy_bounds[3] = max(xy_bounds[3], y)
                assert -0.01 <= x <= 270.01, (path.name, x)
                assert -0.01 <= y <= 200.01, (path.name, y)
    assert temperature_commands and max(temperature_commands) <= min(240,nozzle_c)
    assert 0 < max_brim_speed <= 15.01, (path.name, "missing or excessive brim speed")

    def extract(pattern: str) -> str:
        match = re.search(pattern, text)
        assert match, (path.name, pattern)
        return match.group(1)

    max_z = float(extract(r"; max_z_height: ([\d.]+)"))
    # Fixed 0.20 mm layers quantize a 36.88 mm side-printed foot to 36.8 mm.
    # Check the expected layer height rather than demanding a fractional layer.
    layer_height = float(required_settings["layer_height"])
    # At exactly half a layer Orca can choose either adjacent layer, depending
    # on tessellation/float rounding. Both are nearest-layer representations.
    assert abs(max_z - expected_height) <= layer_height / 2 + 0.001, (path.name, max_z, expected_height)
    assert abs(max_z / layer_height - round(max_z / layer_height)) < .001, (path.name, max_z)
    return {
        "gcode_file": path.name,
        "slicer": extract(r"generated by (OrcaSlicer [^\s]+)"),
        "gcode_sha256": sha256(path),
        "size_bytes": path.stat().st_size,
        "layers": int(extract(r"; total layers count = (\d+)")),
        "estimated_time": extract(r"; estimated printing time \(normal mode\) = (.+)"),
        "estimated_filament_g": float(extract(r"; total filament used \[g\] = ([\d.]+)")),
        "max_z_mm": max_z,
        "supports_enabled": supports_required,
        "source_height_mm": expected_height,
        "height_quantization_mm": round(max_z - expected_height, 4),
        "toolpath_xy_bounds_mm": [round(v, 3) for v in xy_bounds],
        "max_nozzle_command_c": max(temperature_commands),
        "nozzle_diameter_mm": 0.4,
        "bed_command_c":bed_c,
        "material":"Polymaker HT-PLA-GF" if ht_pla_gf else "Duramic PETG",
        "max_print_speed_mm_s": round(max_print_speed, 3),
        "max_first_layer_print_speed_mm_s": round(max_first_layer_speed, 3),
        "max_brim_speed_mm_s": round(max_brim_speed, 3),
        "max_travel_speed_mm_s": round(max_travel_speed, 3),
        "max_print_acceleration_mm_s2": max_print_acceleration,
        "max_first_layer_print_acceleration_mm_s2": max_first_layer_acceleration,
        "max_travel_acceleration_mm_s2": max_travel_acceleration,
    }


def main(selected: list[str]) -> None:
    machine = find_machine()
    orca = find_orca()
    machine_preset = json.loads(machine.read_text())
    assert machine_preset["nozzle_diameter"] == ["0.4"], "These jobs require the installed 0.4 mm nozzle"
    jobs = json.loads((JOBS / "manifest.json").read_text())["jobs"]
    unknown = set(selected) - set(jobs)
    assert not unknown, f"unknown plates: {sorted(unknown)}"
    GCODE.mkdir(exist_ok=True)
    summary_path = GCODE / "manifest.json"
    summary = json.loads(summary_path.read_text()) if selected and summary_path.exists() else {"jobs": {}}
    summary.update({
        "status": "provisional fit prototypes; physical shelf and component interfaces unmeasured",
        "printer": "Qidi X-Plus first generation, 0.4 mm nozzle",
        "machine_profile": machine.name,
        "machine_profile_sha256": sha256(machine),
        "material_selection": "Per-plate filament profile; PSU and GPU cooling/duct plates use HT-PLA-GF and need a 0.4 mm hardened steel nozzle.",
    })
    for stem, item in jobs.items():
        if selected and stem not in selected:
            continue
        source = JOBS / f"{stem}.3mf"
        destination = GCODE / f"{stem}.gcode"
        process_profile = JOBS / item["process_profile"]
        filament_profile = JOBS / item["filament_profile"]
        ht_pla_gf = "ht-pla-gf" in filament_profile.name
        if ht_pla_gf:
            assert machine_preset["nozzle_type"] == "hardened_steel", "HT-PLA-GF needs a hardened steel nozzle"
        # Flatpak has a private /tmp. Keep intermediate files beside the output
        # so the host Python process and the slicer see the same directory.
        with tempfile.TemporaryDirectory(prefix=f".slice-{stem}-", dir=GCODE) as temp_name:
            temp = Path(temp_name)
            command = [
                *orca,
                "--debug", "3", "--logfile", str(temp / "orca.log"),
                "--load-settings", f"{machine};{process_profile}",
                "--load-filaments", str(filament_profile),
                "--arrange", "0", "--orient", "0", "--slice", "0",
                "--outputdir", str(temp), str(source),
            ]
            print(f"Slicing {source.name}...", flush=True)
            run = subprocess.run(command, cwd=temp, text=True, capture_output=True)
            log_path = GCODE / f"{stem}.log"
            diagnostics = (
                f"Command: {shlex.join(command)}\nExit status: {run.returncode}\n"
                f"\nstdout:\n{run.stdout}\n\nstderr:\n{run.stderr}\n"
            )
            for log in sorted(temp.glob("*.log")):
                diagnostics += f"\n{log.name}:\n{log.read_text(errors='replace')}\n"
            log_path.write_text(diagnostics)
            failure_details = f"Full slicer log: {log_path}\n{diagnostics[-4000:]}"
            if run.returncode:
                raise RuntimeError(f"{stem} failed ({run.returncode}):\n{failure_details}")
            try:
                result = json.loads((temp / "result.json").read_text())
            except (OSError, ValueError) as exc:
                raise RuntimeError(
                    f"{stem}: OrcaSlicer exited with status 0 but did not produce a readable "
                    f"result.json. Check slicer output and directory access.\n{failure_details}"
                ) from exc
            if not isinstance(result, dict) or result.get("return_code") != 0:
                raise RuntimeError(f"{stem}: slicing failed: {result}\n{failure_details}")
            sliced = temp / "plate_1.gcode"
            if not sliced.is_file():
                raise RuntimeError(f"{stem}: OrcaSlicer did not produce plate_1.gcode.\n{failure_details}")
            checked = validate_gcode(sliced, item["highest_part_mm"], item["supports_required"],
                                     nozzle_c=230 if ht_pla_gf else 240, bed_c=50 if ht_pla_gf else 75,
                                     ht_pla_gf=ht_pla_gf)
            checked["gcode_file"] = destination.name
            shutil.move(sliced, destination)
        summary["jobs"][stem] = {"source_3mf_sha256": sha256(source), "copies": item["copies"],
            "process_profile": item["process_profile"], "process_profile_sha256": sha256(process_profile),
            "filament_profile": item["filament_profile"], "filament_profile_sha256": sha256(filament_profile),
            "required_nozzle": item["required_nozzle"], **checked}
        print(f"  {checked['estimated_time']}, {checked['estimated_filament_g']} g, print x{item['copies']}", flush=True)
    summary_path.write_text(json.dumps(summary, indent=2) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
