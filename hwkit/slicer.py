"""Slice the build's print plates (print/*.3mf) for its printer with OrcaSlicer.

Run with ``hwkit slice [plate ...]`` after ``hwkit plates``. Needs OrcaSlicer
2.5.x (macOS app, Linux AppImage/binary or Flatpak). The printer's base presets
are vendored in hwkit/printers/<printer>/orca-<version>/ because OrcaSlicer 2.5
packs its installed system presets into .opc files the CLI cannot load. This
module resolves each profile's inherits chain and passes OrcaSlicer flattened
presets, then checks every G-code file against the printer's policy in
printer.toml. Override slicer detection with ORCA="<command>". The G-code is
gitignored and regenerated by make.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from hwkit import paths, printers

JOBS = paths.PRINT
GCODE = JOBS / "gcode"
PRINTER = printers.get()
ORCA_VERSION = PRINTER.config["orca_version"]
ORCA_BASE = PRINTER.orca_base
MACHINE_PRESET = PRINTER.machine_preset
ORCA_MAC_APP = Path("/Applications/OrcaSlicer.app/Contents/MacOS/OrcaSlicer")


def base_presets() -> dict[str, dict]:
    presets = {}
    for path in sorted(ORCA_BASE.glob("*/*.json")):
        preset = json.loads(path.read_text())
        assert preset["name"] not in presets, (path, "duplicate base preset name")
        presets[preset["name"]] = preset
    return presets


def flatten(preset: dict, bases: dict[str, dict], seen: tuple[str, ...] = ()) -> dict:
    """Merge a preset over its inherits chain, the way OrcaSlicer does."""
    parent = preset.get("inherits")
    if not parent:
        merged = dict(preset)
    else:
        assert parent in bases, f"{preset['name']}: base preset {parent!r} is not vendored in {ORCA_BASE}"
        assert parent not in seen, f"inherits cycle: {' <- '.join((*seen, parent))}"
        assert bases[parent]["type"] == preset["type"], (preset["name"], "inherits a different preset type", parent)
        merged = {**flatten(bases[parent], bases, (*seen, preset["name"])), **preset}
    merged["inherits"] = ""
    return merged


def write_flat(source: Path, bases: dict[str, dict], destination: Path) -> Path:
    preset = flatten(json.loads(source.read_text()), bases)
    preset["from"] = "User"
    destination.write_text(json.dumps(preset, indent=4, sort_keys=True) + "\n")
    return destination


def find_orca() -> list[str]:
    if "ORCA" in os.environ:
        return shlex.split(os.environ["ORCA"])
    if ORCA_MAC_APP.exists():
        return [str(ORCA_MAC_APP)]
    for name in ("orca-slicer", "OrcaSlicer"):
        if shutil.which(name):
            return [name]
    if shutil.which("flatpak"):
        return ["flatpak", "run", "com.orcaslicer.OrcaSlicer"]
    raise SystemExit("OrcaSlicer not found; install it or set ORCA")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def validate_gcode(path: Path, expected_height: float, supports_required: bool, material: dict, process: dict) -> dict:
    """Check one G-code file against the printer policy, the material and the flattened process profile."""
    policy = PRINTER.config["gcode"]
    limits = policy["limits"]
    bed_w, bed_d = PRINTER.bed
    nozzle_c, bed_c = material["nozzle_c"], material["bed_c"]
    brim = process.get("brim_type") != "no_brim"
    text = path.read_text()
    assert re.search(r"generated by OrcaSlicer \d", text), path.name
    assert f"generated by OrcaSlicer {ORCA_VERSION}" in text, (path.name, f"vendored presets are for OrcaSlicer {ORCA_VERSION}x")
    assert f"bed_shape = 0x0,{bed_w:g}x0,{bed_w:g}x{bed_d:g},0x{bed_d:g}" in text
    assert f"M190 S{bed_c}" in text and f"M109 S{nozzle_c}" in text
    # Material settings (for example the hardened-nozzle profile check) and a
    # disabled skirt, when the process profile turns it off.
    for key, value in material.get("gcode_settings", {}).items():
        assert re.search(rf"^; {key} = {re.escape(value)}$", text, re.MULTILINE), (path.name, key)
    if process.get("skirt_loops") == "0":
        assert "; skirt_loops = 0" in text
    if brim:
        assert ";TYPE:Brim" in text
    else:
        assert "; brim_type = no_brim" in text and ";TYPE:Brim" not in text, (path.name, "brim must be off")
    assert "; layer_change_gcode = G92 E0" in text or "\nG92 E0\n" in text
    assert f"; enable_support = {int(supports_required)}" in text
    if supports_required:
        assert ";TYPE:Support" in text and ";TYPE:Support interface" in text, "No actual support paths"
        for key, value in policy["support_settings"].items():
            assert re.search(rf"^; {key} = {re.escape(value)}$", text, re.MULTILINE), (path.name, key)
    required_settings = policy["settings"]
    for key, value in required_settings.items():
        assert re.search(rf"^; {key} = {re.escape(value)}$", text, re.MULTILINE), (path.name, key)
    assert "M104 S0" in text and "M140 S0" in text

    temperature_commands = []
    xy_bounds = [float("inf"), float("inf"), float("-inf"), float("-inf")]
    x = y = 0.0
    extrusion = feed_mm_min = 0.0
    relative_extrusion = False
    layer_number = 0
    print_acceleration = travel_acceleration = None
    max_print_speed = max_travel_speed = max_first_layer_speed = 0.0
    max_print_acceleration = max_travel_acceleration = 0.0
    max_first_layer_acceleration = 0.0
    role = ""
    max_brim_speed = 0.0
    for raw in text.splitlines():
        if raw.startswith(";TYPE:"):
            role = raw.removeprefix(";TYPE:").strip()
        if raw == ";LAYER_CHANGE":
            layer_number += 1
        line = raw.split(";", 1)[0].strip()
        if not line:
            continue
        command = line.split()[0]
        parameters = {key: float(value) for key, value in re.findall(r"\b([A-Z])(-?(?:\d+(?:\.\d*)?|\.\d+))", line)}
        assert command not in {"G91", "G2", "G3"}, (path.name, "unsupported motion mode", line)
        if command in {"M82", "M83"}:
            relative_extrusion = command == "M83"
        if command == "G92" and "E" in parameters:
            extrusion = parameters["E"]
        if command == "M204":
            if "S" in parameters:
                print_acceleration = travel_acceleration = parameters["S"]
            print_acceleration = parameters.get("P", print_acceleration)
            travel_acceleration = parameters.get("T", travel_acceleration)
        if command in {"M104", "M109"}:
            match = re.search(r"\b[SR](-?\d+(?:\.\d+)?)", line)
            if match:
                temperature_commands.append(float(match.group(1)))
        if command in {"G0", "G1"}:
            feed_mm_min = parameters.get("F", feed_mm_min)
            delta_e = parameters.get("E", 0.0) if relative_extrusion else parameters.get("E", extrusion) - extrusion
            if "E" in parameters:
                extrusion = extrusion + delta_e if relative_extrusion else parameters["E"]
            xy_move = parameters.get("X", x) != x or parameters.get("Y", y) != y
            if xy_move and layer_number:
                speed = feed_mm_min / 60
                if delta_e > 0:
                    assert speed <= limits["print_speed"] + 0.01, (path.name, "print speed", speed)
                    assert print_acceleration is not None and print_acceleration <= limits["print_acceleration"], (
                        path.name,
                        "print acceleration",
                        print_acceleration,
                    )
                    max_print_speed = max(max_print_speed, speed)
                    max_print_acceleration = max(max_print_acceleration, print_acceleration)
                    if role == "Brim":
                        assert speed <= limits["brim_speed"] + 0.01, (path.name, "brim speed", speed)
                        max_brim_speed = max(max_brim_speed, speed)
                    if layer_number == 1:
                        assert speed <= limits["first_layer_speed"] + 0.01 and print_acceleration <= limits["first_layer_acceleration"], (
                            path.name,
                            "first layer",
                            speed,
                            print_acceleration,
                        )
                        max_first_layer_speed = max(max_first_layer_speed, speed)
                        max_first_layer_acceleration = max(max_first_layer_acceleration, print_acceleration)
                else:
                    assert speed <= limits["travel_speed"] + 0.01, (path.name, "travel speed", speed)
                    assert travel_acceleration is not None and travel_acceleration <= limits["travel_acceleration"], (
                        path.name,
                        "travel acceleration",
                        travel_acceleration,
                    )
                    max_travel_speed = max(max_travel_speed, speed)
                    max_travel_acceleration = max(max_travel_acceleration, travel_acceleration)
            x = parameters.get("X", x)
            y = parameters.get("Y", y)
            if "X" in parameters or "Y" in parameters:
                xy_bounds[0] = min(xy_bounds[0], x)
                xy_bounds[1] = min(xy_bounds[1], y)
                xy_bounds[2] = max(xy_bounds[2], x)
                xy_bounds[3] = max(xy_bounds[3], y)
                assert -0.01 <= x <= bed_w + 0.01, (path.name, x)
                assert -0.01 <= y <= bed_d + 0.01, (path.name, y)
    assert temperature_commands and max(temperature_commands) <= min(limits["nozzle_c"], nozzle_c)
    assert (0 < max_brim_speed <= limits["brim_speed"] + 0.01) if brim else max_brim_speed == 0, (
        path.name,
        "missing or excessive brim speed",
    )

    def extract(pattern: str) -> str:
        match = re.search(pattern, text)
        assert match, (path.name, pattern)
        return match.group(1)

    max_z = float(extract(r"; max_z_height: ([\d.]+)"))
    # Fixed 0.20 mm layers quantize a 36.88 mm side-printed foot to 36.8 mm.
    # Check the expected layer height rather than demanding a fractional layer.
    layer_height = float(required_settings["layer_height"])
    # At exactly half a layer Orca can choose either adjacent layer, depending
    # on tessellation/float rounding. Both are nearest-layer representations.
    assert abs(max_z - expected_height) <= layer_height / 2 + 0.001, (path.name, max_z, expected_height)
    assert abs(max_z / layer_height - round(max_z / layer_height)) < 0.001, (path.name, max_z)
    return {
        "gcode_file": path.name,
        "slicer": extract(r"generated by (OrcaSlicer [^\s]+)"),
        "gcode_sha256": sha256(path),
        "size_bytes": path.stat().st_size,
        "layers": int(extract(r"; total layers count = (\d+)")),
        "estimated_time": extract(r"; estimated printing time \(normal mode\) = (.+)"),
        "estimated_filament_g": float(extract(r"; total filament used \[g\] = ([\d.]+)")),
        "max_z_mm": max_z,
        "supports_enabled": supports_required,
        "source_height_mm": expected_height,
        "height_quantization_mm": round(max_z - expected_height, 4),
        "toolpath_xy_bounds_mm": [round(v, 3) for v in xy_bounds],
        "max_nozzle_command_c": max(temperature_commands),
        "nozzle_diameter_mm": PRINTER.config["nozzle_mm"],
        "bed_command_c": bed_c,
        "material": material["name"],
        "max_print_speed_mm_s": round(max_print_speed, 3),
        "max_first_layer_print_speed_mm_s": round(max_first_layer_speed, 3),
        "max_brim_speed_mm_s": round(max_brim_speed, 3),
        "max_travel_speed_mm_s": round(max_travel_speed, 3),
        "max_print_acceleration_mm_s2": max_print_acceleration,
        "max_first_layer_print_acceleration_mm_s2": max_first_layer_acceleration,
        "max_travel_acceleration_mm_s2": max_travel_acceleration,
    }


def main(selected: list[str]) -> None:
    bases = base_presets()
    orca = find_orca()
    machine_preset = flatten(json.loads(MACHINE_PRESET.read_text()), bases)
    nozzle = f"{PRINTER.config['nozzle_mm']:g}"
    assert machine_preset["nozzle_diameter"] == [nozzle], f"These jobs require the installed {nozzle} mm nozzle"
    jobs = json.loads((JOBS / "manifest.json").read_text())["jobs"]
    unknown = set(selected) - set(jobs)
    assert not unknown, f"unknown plates: {sorted(unknown)}"
    GCODE.mkdir(exist_ok=True)
    summary_path = GCODE / "manifest.json"
    summary = json.loads(summary_path.read_text()) if selected and summary_path.exists() else {"jobs": {}}
    summary.update(
        {
            "status": "provisional fit prototypes; physical shelf and component interfaces unmeasured",
            "printer": PRINTER.name,
            "machine_profile": MACHINE_PRESET.name,
            "orca_base_presets": ORCA_BASE.name,
            "orca_base_presets_sha256": {p.relative_to(ORCA_BASE).as_posix(): sha256(p) for p in sorted(ORCA_BASE.glob("*/*.json"))},
            "material_selection": "Per-plate filament profile; see each job's filament_profile and required_nozzle.",
        }
    )
    for stem, item in jobs.items():
        if selected and stem not in selected:
            continue
        source = JOBS / f"{stem}.3mf"
        destination = GCODE / f"{stem}.gcode"
        process_profile = PRINTER.profile(item["process_profile"])
        filament_profile = PRINTER.profile(item["filament_profile"])
        material = PRINTER.materials[filament_profile.name]
        if material.get("hardened_nozzle"):
            # Profile check only: the stock preset always says hardened_steel.
            # The printer must actually have the hardened steel nozzle fitted.
            assert machine_preset["nozzle_type"] == "hardened_steel", f"{material['name']} needs a hardened steel nozzle profile"
        # Flatpak has a private /tmp. Keep intermediate files beside the output
        # so the host Python process and the slicer see the same directory.
        with tempfile.TemporaryDirectory(prefix=f".slice-{stem}-", dir=GCODE) as temp_name:
            temp = Path(temp_name)
            machine = write_flat(MACHINE_PRESET, bases, temp / "machine.json")
            process_flat = write_flat(process_profile, bases, temp / "process.json")
            filament_flat = write_flat(filament_profile, bases, temp / "filament.json")
            command = [
                *orca,
                "--debug",
                "3",
                "--logfile",
                str(temp / "orca.log"),
                "--load-settings",
                f"{machine};{process_flat}",
                "--load-filaments",
                str(filament_flat),
                "--arrange",
                "0",
                "--orient",
                "0",
                "--slice",
                "0",
                "--outputdir",
                str(temp),
                str(source),
            ]
            print(f"Slicing {source.name}...", flush=True)
            run = subprocess.run(command, cwd=temp, text=True, capture_output=True)
            log_path = GCODE / f"{stem}.log"
            diagnostics = (
                f"Command: {shlex.join(command)}\nExit status: {run.returncode}\n\nstdout:\n{run.stdout}\n\nstderr:\n{run.stderr}\n"
            )
            for log in sorted(temp.glob("*.log")):
                diagnostics += f"\n{log.name}:\n{log.read_text(errors='replace')}\n"
            log_path.write_text(diagnostics)
            failure_details = f"Full slicer log: {log_path}\n{diagnostics[-4000:]}"
            if run.returncode:
                raise RuntimeError(f"{stem} failed ({run.returncode}):\n{failure_details}")
            # OrcaSlicer 2.5.0 writes result.json; 2.5.1 does not. When it is
            # there it must report success; the exit status, plate_1.gcode and
            # validate_gcode() below are checked either way.
            result_path = temp / "result.json"
            if result_path.exists():
                try:
                    result = json.loads(result_path.read_text())
                except ValueError as exc:
                    raise RuntimeError(f"{stem}: unreadable result.json.\n{failure_details}") from exc
                if not isinstance(result, dict) or result.get("return_code") != 0:
                    raise RuntimeError(f"{stem}: slicing failed: {result}\n{failure_details}")
            sliced = temp / "plate_1.gcode"
            if not sliced.is_file():
                raise RuntimeError(f"{stem}: OrcaSlicer did not produce plate_1.gcode.\n{failure_details}")
            checked = validate_gcode(
                sliced,
                item["highest_part_mm"],
                item["supports_required"],
                material,
                flatten(json.loads(process_profile.read_text()), bases),
            )
            checked["gcode_file"] = destination.name
            shutil.move(sliced, destination)
        summary["jobs"][stem] = {
            "source_3mf_sha256": sha256(source),
            "copies": item["copies"],
            "process_profile": item["process_profile"],
            "process_profile_sha256": sha256(process_profile),
            "filament_profile": item["filament_profile"],
            "filament_profile_sha256": sha256(filament_profile),
            "required_nozzle": item["required_nozzle"],
            **checked,
        }
        print(f"  {checked['estimated_time']}, {checked['estimated_filament_g']} g, print x{item['copies']}", flush=True)
    summary_path.write_text(json.dumps(summary, indent=2) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
