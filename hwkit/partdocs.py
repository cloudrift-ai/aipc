"""Generated part docs: the shared library's READMEs and each build's part pages.

parts/README.md, parts/<category>/<id>/README.md   library index and specs (repo root)
<build>/parts/README.md, <build>/parts/<id>.md      the build's parts, usage and checks
"""

from __future__ import annotations

import os
import tomllib

from . import paths, spec

ICON = {"FAIL": "FAIL", "BLOCKED": "BLOCKED", "PROVISIONAL": "provisional", "PASS": "pass"}


def _fmt(v):
    if v is None:
        return "**unknown**"
    return f"{v:g}" if isinstance(v, float) else str(v)


def _iface(i):
    bits = [f"`{i['type']}`"]
    for key in ("value", "accepts", "count", "capacity", "load", "load_limited", "min", "max"):
        if key in i:
            bits.append(f"{key} {_fmt(i[key])}")
    if i.get("unit"):
        bits.append(i["unit"])
    bits.append(f"({i['evidence']})")
    if i.get("note"):
        bits.append(f"— {i['note']}")
    return " ".join(bits)


def _rel(target, start) -> str:
    return os.path.relpath(target, start)


def _usage_rows() -> dict[str, list[tuple[str, dict]]]:
    """Library part id -> [(build, raw usage)] for every build in the repo."""
    rows: dict[str, list[tuple[str, dict]]] = {}
    for build in paths.builds():
        for toml in sorted((build / "parts").glob("*.toml")):
            use = tomllib.loads(toml.read_text())
            rows.setdefault(use.get("part", "").rpartition("/")[2], []).append((build.name, use))
    return rows


def _dims_table(dims) -> list[str]:
    L = ["| Key | Value | Evidence | Source / note |", "| --- | --- | --- | --- |"]
    for d in dims:
        src = "; ".join(x for x in (d.source, d.note) if x)
        L.append(f"| {d.key} | {_fmt(d.value)} {d.unit if d.value is not None else ''} | {d.evidence} | {src} |")
    return L + [""]


def library_readme(p, used_in) -> str:
    """The library spec of one part: what it is, independent of any build."""
    L = [
        f"# {p.name}",
        "",
        "<!-- Generated by make check from part.toml. Edit part.toml, not this file. -->",
        "",
        "| | |",
        "| --- | --- |",
        f"| ID | `{p.id}` |",
        f"| Category | {p.category} |",
    ]
    if p.data.get("print"):
        pr = p.data["print"]
        L.append(f"| Print | {pr.get('material')}; plates are in each build's print/ |")
    for k, v in p.data.get("links", {}).items():
        L.append(f"| {k.capitalize()} | <{v}> |")
    L.append("")
    if p.data.get("notes"):
        L += [p.data["notes"].strip(), ""]
    if p.render_png.exists():
        L += ["![Part views](render.png)", ""]

    L += ["## Used in", ""]
    if used_in:
        L += ["| Build | Qty | Status | Role |", "| --- | ---: | --- | --- |"]
        for build, use in used_in:
            page = _rel(paths.REPO / build / "parts" / f"{p.id}.md", p.dir)
            L.append(f"| [{build}]({page}) | {use.get('quantity', '')} | {use.get('status', '')} | {use.get('role', '')} |")
    else:
        L.append("- No build references this part.")
    L.append("")

    L += ["## Model", ""]
    m = p.data.get("model", {})
    if p.model_step.exists():
        L.append(
            f"- [{p.model_step.name}]({p.model_step.name})"
            + (f" and [{p.model_stl.name}]({p.model_stl.name})" if p.model_stl.exists() else "")
        )
    L.append(f"- Source: {m.get('source', 'unknown')}" + (f". {m['notes']}" if m.get("notes") else ""))
    if m.get("vendor_cad"):
        L.append(f"- Vendor CAD: {m['vendor_cad']}")
    if p.model_build:
        L.append(f"- Written by the `{p.model_build}` build's generator")
    L.append("")

    L += ["## Datasheets", ""]
    if p.datasheets:
        L += [f"- [{d['title']}]({d['url']})" for d in p.datasheets]
        L.append("- Local copies: `datasheets/` after `make datasheets` (not committed)")
    else:
        L.append(f"- None recorded. {p.data.get('no_datasheet_reason', '')}")
    L.append("")

    if p.dims:
        L += ["## Dimensions", ""] + _dims_table(p.dims.values())
    if p.provides or p.requires:
        L += ["## Interfaces", ""]
        L += [f"- provides {_iface(i)}" for i in p.provides]
        L += [f"- requires {_iface(i)}" for i in p.requires]
        L.append("")
    return "\n".join(L)


def build_page(p, checks, bom_row) -> str:
    """How the current build uses one part: role, overrides, assembly and its checks."""
    spec_readme = _rel(p.dir / "README.md", paths.PARTS)
    L = [
        f"# {p.name}",
        "",
        f"<!-- Generated by make check from {p.id}.toml and the library part.toml. Edit those, not this file. -->",
        "",
        f"Library spec: [parts/{p.category}/{p.id}]({spec_readme}) (dimensions, interfaces, datasheets, model).",
        "",
        "| | |",
        "| --- | --- |",
        f"| Role | {p.role} |",
        f"| Status | {p.status} |",
        f"| Quantity | {p.quantity} |",
        f"| Systems | {', '.join(p.systems)} |",
        "",
    ]
    if p.use_notes:
        L += [p.use_notes.strip(), ""]
    if p.in_assembly_png.exists():
        L += [f"![Part in the assembly]({_rel(p.in_assembly_png, paths.PARTS)})", ""]

    use_dims = p.use.get("dims", {})
    changes = [(kind, i) for kind in ("provides", "requires") for i in p.use.get(kind, [])]
    if use_dims or changes:
        L += ["## Changes for this build", ""]
        if use_dims:
            L += _dims_table(d for d in p.dims.values() if d.key in use_dims)
        for kind, i in changes:
            fields = ", ".join(f"{k} {_fmt(v)}" for k, v in i.items() if k not in ("type", "replaces", "remove", "note"))
            if i.get("remove"):
                action = "removed"
            elif i.get("replaces"):
                action = f"replaces `{i['replaces']}`" + (f", sets {fields}" if fields else "")
            else:
                action = f"sets {fields}" if fields else "no field changes"
            line = f"- {kind} `{i['type']}`: {action}"
            L.append(line + (f" — {i['note']}" if i.get("note") else ""))
        if changes:
            L.append("")

    if bom_row:
        state = bom_row["state"]
        detail = {
            "modeled": f"{bom_row['instances']} instances in the assembly",
            "covered": f"inside the envelope of [{bom_row['covered_by']}]({bom_row['covered_by']}.md)",
            "not_modeled": f"**not in the assembly**: {bom_row['not_modeled']}",
        }.get(state, state)
        L += ["## Assembly", "", f"- {detail}", ""]
    mine = [c for c in checks if p.id in c.get("requirers", []) or p.id in c.get("providers", []) or p.id in c.get("contributors", [])]
    if mine:
        L += ["## Compatibility checks", "", "| Status | Rule | Interface | Detail |", "| --- | --- | --- | --- |"]
        L += [f"| {ICON[c['status']]} | {c['rule']} | `{c['type']}` | {c['detail'].replace('|', '/')} |" for c in mine]
        L.append("")
    return "\n".join(L)


def write_library_docs():
    """README per library part and the library index. Depends only on the specs, so every build writes the same."""
    library = spec.load_library()
    users = spec.library_users()
    rows = _usage_rows()
    for p in library.values():
        (p.dir / "README.md").write_text(library_readme(p, rows.get(p.id, [])) + "\n")
    L = [
        "# Parts library",
        "",
        "<!-- Generated by make check. Edit each part.toml, not this file. -->",
        "",
        "One folder per part, shared by every build: `part.toml` (identity, dimensions, interfaces, datasheets "
        "and evidence), a generated `README.md`, the model (`<id>.step`, and `<id>.stl` for printed parts), "
        "`render.png` and fetched `datasheets/`. A build uses a part through its own `<build>/parts/<id>.toml`, "
        "which sets the quantity, role, status, systems and assembly mapping and may add build-specific "
        f"dimensions or interface changes. See [docs/process.md]({_rel(paths.REPO / 'docs' / 'process.md', paths.LIBRARY)}).",
        "",
    ]
    for category in paths.CATEGORIES:
        parts = sorted((p for p in library.values() if p.category == category), key=lambda p: p.id)
        if not parts:
            continue
        L += [f"## {category.capitalize()}", "", "| Part | Name | Used in |", "| --- | --- | --- |"]
        for p in parts:
            builds = ", ".join(f"[{b}]({_rel(paths.REPO / b / 'parts' / f'{p.id}.md', paths.LIBRARY)})" for b in users.get(p.id, []))
            L.append(f"| [{p.id}]({category}/{p.id}/README.md) | {p.name} | {builds or 'none'} |")
        L.append("")
    (paths.LIBRARY / "README.md").write_text("\n".join(L) + "\n")


def write_part_docs(parts, checks, bom):
    write_library_docs()
    for stale in paths.PARTS.glob("*.md"):
        if stale.name != "README.md" and stale.stem not in parts:
            stale.unlink()
    for p in parts.values():
        p.page.write_text(build_page(p, checks, bom["parts"].get(p.id)) + "\n")
    worst = {}
    order = ["FAIL", "BLOCKED", "PROVISIONAL", "PASS"]
    for c in checks:
        for pid in set(c.get("requirers", [])) | set(c.get("providers", [])):
            if pid in parts and (pid not in worst or order.index(c["status"]) < order.index(worst[pid])):
                worst[pid] = c["status"]
    L = [
        "# Parts",
        "",
        "<!-- Generated by make check. Edit each <id>.toml or the library part.toml, not this file. -->",
        "",
        f"The parts this build uses. Each `<id>.toml` here references a spec in the shared "
        f"[parts library]({_rel(paths.LIBRARY / 'README.md', paths.PARTS)}) and sets the quantity, role, status, "
        "systems and assembly mapping for this build; `<id>.md` is the generated page with the checks. "
        "See [docs/system-check.md](../docs/system-check.md) for the latest compatibility results.",
        "",
    ]
    for category in paths.CATEGORIES:
        rows = [p for p in parts.values() if p.category == category]
        if not rows:
            continue
        L += [
            f"## {category.capitalize()}",
            "",
            "| Part | Qty | Status | Systems | Worst check | Role |",
            "| --- | ---: | --- | --- | --- | --- |",
        ]
        for p in sorted(rows, key=lambda p: p.id):
            L.append(
                f"| [{p.id}]({p.id}.md) | {p.quantity} | {p.status} | {', '.join(p.systems)} | "
                f"{ICON.get(worst.get(p.id), '-')} | {p.role} |"
            )
        L.append("")
    (paths.PARTS / "README.md").write_text("\n".join(L) + "\n")
